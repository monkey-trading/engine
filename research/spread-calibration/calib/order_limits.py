"""Resting-order limits by volume tier (#614, decision D11; #700): what they are worth against wallet
recycling, and what they cost the sequencer.

**Worth.** A toxic account the stick catches can move to a fresh wallet, which starts at tier 0's
25 resting orders. The strategies #549 and #623 measured trade with market orders: latency
arbitrage opens and closes at the live price, and unpriced pairs open before a spell and close
after it. A resting order fills at the engine's price when the engine's price reaches it, which
gives no lead over the venues, so none of them rests an order and none forfeits anything when its
limit falls to 25. What recycling forfeits is the other carrots' value (`carrot.best_responses`,
`at_recycler_best`).

**Cost.** A price visits every resting order its mid has reached, and a limit that the spread keeps
out of reach stays resting, so it is visited and priced again on every price.
`crates/node/src/sequencer/resting_bench.rs` loads that many such limits into one market of a
100k-account sequencer and times the price command's stamp, which every later price waits behind;
`price_wait_budget` holds a batch's median wait to 1 ms. The per-account limits do not bound that
work: a fresh wallet that has deposited holds 25, so the number of such orders in a market grows
with the number of wallets, not with any one account's tier.
"""

import re

import numpy as np

TIER_LIMITS = (25, 50, 100, 250)
BUDGET_MEDIAN_US = 1_000
LINE = re.compile(r"WAIT price_stamp_rechecking_(\d+)_resting_orders samples=(\d+) p50_us=(\d+) p99_us=(\d+) max_us=(\d+)")
AWAY = re.compile(r"WAIT price_stamp_with_(\d+)_resting_orders_away samples=(\d+) p50_us=(\d+) p99_us=(\d+) max_us=(\d+)")


def parse_bench(text: str, line: re.Pattern = LINE) -> list[dict]:
    """The benchmark's rows: orders, samples, and the price stamp's p50, p99 and worst; out-of-reach
    orders with `LINE`, orders away from the price with `AWAY`."""
    return [{"orders": int(m[1]), "samples": int(m[2]), "p50_us": int(m[3]), "p99_us": int(m[4]), "max_us": int(m[5])}
            for m in line.finditer(text)]


def per_order_us(rows: list[dict]) -> tuple[float, float]:
    """The median stamp with no orders, and the microseconds each order adds: the mean over the
    other cases of their median less that, per order, so the largest loads do not set it alone."""
    base = float(next(r["p50_us"] for r in rows if r["orders"] == 0))
    loaded = [r for r in rows if r["orders"] > 0]
    x = np.array([r["orders"] for r in loaded], dtype=float)
    y = np.array([r["p50_us"] for r in loaded], dtype=float) - base
    return base, float(np.mean(y / x))


def orders_within(base: float, slope: float, budget_us: float = BUDGET_MEDIAN_US) -> float:
    """How many re-checked orders a price can visit before its own stamp reaches the median budget."""
    return max(0.0, (budget_us - base) / slope)

ACCOUNTS = 100_000


def report(out: dict) -> str:
    """`results/order_limits.md` from the stage's results."""
    from calib.report import table, usd

    cost = out["cost"]
    lines = ["# Resting-order limits by volume tier (#700)", "",
             "Generated by `python -I run.py order_limits`. What each limit is worth against wallet recycling, and what resting "
             "orders cost a price.", "", "## Worth: what recycling forfeits", "",
             "The latency strategy at the owner's fee (100% to 1 s, 10% at 15 minutes), after the spreads, the size tiers and "
             "the stick, on an operator-sized position: the better of keeping a wallet and recycling one at tier 0, and at the "
             "recycler's best what it gains (the stick's add-on) and forfeits (the kept tier's best-price size and leverage, "
             "and the wallets), each as the account's profit a day. It trades with market orders, so moving to tier 0's 25 resting orders "
             "forfeits nothing.", ""]
    body = []
    for k, v in out["worth"].items():
        body.append([k.replace("@", ", "), usd(v["keeper_per_day"]), usd(v["recycler_per_day"]), usd(v.get("gain_per_day")),
                     usd(v.get("forfeited_per_day")), usd(v["resting_orders_per_day"])])
    lines += table(["Market, lead", "Keeping a wallet", "Recycling", "Add-on avoided", "Other carrots and wallets forfeited",
                    "Resting-order limit forfeited"], body)
    lines += ["## Cost: what resting orders add to a price", "",
              "`crates/node/src/sequencer/resting_bench.rs`: a 100k-account sequencer with market 1's first spread band at 2 "
              "bps and that many limit buys inside it, which every price reaches and the spread keeps out of reach, so each "
              "stays resting and is priced again on every price. The price command's stamp, which every later price waits "
              "behind, against `price_wait_budget`'s 1 ms median. Run on a shared machine under load.", ""]
    lines += table(["Out-of-reach resting orders", "Samples", "Stamp p50", "p99", "Worst"],
                   [[f"{r['orders']:,}", r["samples"], f"{r['p50_us'] / 1000:.2f} ms", f"{r['p99_us'] / 1000:.2f} ms",
                     f"{r['max_us'] / 1000:.2f} ms"] for r in cost["bench"]])
    lines += [f"A price costs {cost['base_us']:.0f} us and {cost['per_order_us']:.2f} us more for each such order, so about "
              f"{cost['orders_within_median_budget']:,.0f} of them in one market take a price's own stamp to the median budget.", ""]
    for r in cost.get("away", []):
        lines += [f"With {r['orders']:,} resting limits away from the price, every account at tier 0's limit, which no price "
                  f"reaches, a price's stamp is {r['p50_us'] / 1000:.2f} ms at the median and {r['p99_us'] / 1000:.2f} ms at the 99th "
                  "percentile: the index skips orders a price has not reached.", ""]
    lines += table(["Tier limit", "Wallets at the limit that reach the budget", "A price with every account at the limit"],
                   [[t["limit"], f"{t['wallets_to_fill_budget']:,.0f}", f"{t['price_stamp_every_account_at_limit_us'] / 1e6:.2f} s"]
                    for t in cost["tiers"]])
    return "\n".join(lines).rstrip() + "\n"
