"""`results/report.md`: the stages' results as tables, and `results/criterion.json`, the launch criterion
at the 10 s curve with the house-loss budget the trigger holds the classes it sees to."""

import json
from pathlib import Path

import numpy as np

from trigger import inputs

OPERATOR_KEEPS = 0.8
CURVE = "100% to 10 s"


def usd(v: float) -> str:
    if v is None:
        return "-"
    a = abs(v)
    sign = "-" if v < 0 else ""
    if a >= 1e6:
        return f"{sign}${a / 1e6:.2f}M"
    if a >= 1e3:
        return f"{sign}${a / 1e3:.0f}k"
    return f"{sign}${a:.0f}"


def pct(v: float, digits: int = 2) -> str:
    return "-" if v is None else f"{100 * v:.{digits}f}%"


def table(head: list, rows: list) -> list:
    return ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)] + ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]


def criterion(results: Path) -> dict:
    """The launch criterion at the 10 s curve: each class's take a day as #623 counts it, the honest
    share on the corrected income model at that curve, and what the classes the trigger can see may
    take in house loss before the criterion fails."""
    spread = inputs.SPREAD / "results"
    latency = json.loads((spread / "owner_latency.json").read_text())["curves"][CURVE]
    fx = json.loads((spread / "owner_fx.json").read_text())["markets"]
    old = json.loads((spread / "owner_criterion.json").read_text())["flows"]
    share = json.loads((results / "share.json").read_text())["runs"]
    fx_operator = sum(r["curves"][CURVE]["3.0s"] for r in fx.values()) * OPERATOR_KEEPS
    fx_fastest = sum(r["curves"][CURVE]["0.25s"] for r in fx.values())
    out = {"curve": inputs.CURVE, "flows": {}}
    for flow in ("current", "target"):
        c = old[flow]["classes"]
        classes = {
            "latency arbitrage, crypto (3 s)": (latency["operator_per_day"], True),
            "latency arbitrage, FX and indices at D6's tenths (3 s)": (fx_operator, True),
            "unpriced pairs at 1% margin, tier 3's fee": (c["unpriced pairs at 1% margin, tier 3's fee"]["operator_per_day"], True),
            "held sync's kill option": (c["held sync's kill option"]["operator_per_day"], True),
            "skimming client fills": (c["skimming client fills"]["operator_per_day"], False),
            "censoring closes": (c["censoring closes"]["operator_per_day"], False),
        }
        s = share[flow]["operator_share_per_day"]
        seen = sum(v for v, sees in classes.values() if sees)
        unseen = sum(v for v, sees in classes.values() if not sees)
        budget = s - unseen
        out["flows"][flow] = {"classes": {k: {"operator_per_day": v, "trigger_sees": sees} for k, (v, sees) in classes.items()},
                              "together": seen + unseen, "seen": seen, "share": s, "share_at_1s": old[flow]["share_bound"],
                              "holds": seen + unseen < s, "operator_budget": budget, "house_loss_budget": budget / OPERATOR_KEEPS,
                              "seen_house_loss": seen / OPERATOR_KEEPS,
                              "stress_day_pairs_house_loss_697": old[flow]["at_bound"]["stress_day_pairs_house_loss"]}
    out["fastest"] = {"crypto": latency["fast_per_day"], "fx_indices": fx_fastest, "total": latency["fast_per_day"] + fx_fastest}
    (results / "criterion.json").write_text(json.dumps(out, indent=1))
    return out


def grid_fire(rows: list, measure: str, w: str, threshold: float, market: str) -> float:
    """The share of a year's hours in which honest flow's reading meets `threshold`, on the sampled hours."""
    mine = [r for r in rows if r["market"] == market and r["weight"] > 0]
    wt = np.array([r["weight"] for r in mine])
    hit = np.array([r["max"][measure][w] >= threshold for r in mine])
    return float((wt * hit).sum() / wt.sum())


def write(results: Path) -> str:
    crit = criterion(results)
    honest = {f: json.loads((results / f"honest_{f}.json").read_text()) for f in ("current", "target")}
    grid = json.loads((results / "grid_current.json").read_text())["rows"]
    stress = {f: json.loads((results / f"stress_{f}.json").read_text()) for f in ("current", "target")}
    latency = json.loads((results / "latency.json").read_text())
    rec = json.loads((results / "recommended.json").read_text())
    out = ["# The house loss-rate trigger (#698)", "", "Generated by `python -I run.py report` from the stages' results.", ""]

    out += ["## The recommended trigger and its alternative", "",
            "The house-wide marked loss (the house's NAV loss to its clients, net of fees and spreads) over the window, against a "
            f"threshold in bps of the total exposure cap ({usd(rec['total_cap_at_reference_nav'])} at #134's retained NAV), raising every "
            "market to level 2. `Room` is what an attacker adds before the reading meets the threshold: a day's, and in the one window "
            "where honest flow gains the most.", ""]
    rows = []
    for flow in ("current", "target"):
        for name, r in rec["flows"][flow].items():
            rows.append([flow, name, usd(r["threshold"]), pct(r["fire_share"]), pct(r["raised_share"]), f"{r['episodes_a_year']:.0f}",
                         f"{r['episode_mean_hours']:.1f}", usd(r["daily_room_mean"]), usd(r["daily_room_p95"]), usd(r["window_room_max"]),
                         usd(r["stress"]["pre_opened"]["house_loss"]), usd(r["stress"]["per_spell"]["house_loss"])])
    out += table(["Flow", "Trigger", "Threshold", "Hours fired", "Time raised", "Raised periods a year", "Mean period, hours",
                  "Room a day, mean", "p95", "Room in the worst window", "2025-10-10, pairs opened ahead", "One pair reopened per spell"],
                 rows) + [""]

    out += ["## The launch criterion at the 10 s curve", "",
            "The operator's take a day by attack class (80% of its own accounts' profit, as #623 counts it), against its honest share "
            "(20% of the house's distributions) on #697's corrected income model with the full fee held to 10 s.", ""]
    rows = []
    for name in crit["flows"]["current"]["classes"]:
        c, t = crit["flows"]["current"]["classes"][name], crit["flows"]["target"]["classes"][name]
        rows.append([name, "yes" if c["trigger_sees"] else "no (clients pay)", usd(c["operator_per_day"]), usd(t["operator_per_day"])])
    for label, key in (("**All together**", "together"), ("Honest share at the 10 s curve (lower bound)", "share"),
                       ("Honest share at D3's 1 s curve (#697)", "share_at_1s"), ("Operator budget for the classes the trigger sees", "operator_budget"),
                       ("**House-loss budget for them**", "house_loss_budget"), ("House loss they take, unbounded", "seen_house_loss")):
        rows.append([label, "", usd(crit["flows"]["current"][key]), usd(crit["flows"]["target"][key])])
    out += table(["Class", "Trigger sees it", "Current flow", "Target flow"], rows) + [""]
    out += [f"The fastest honest client (0.25 s) takes {usd(crit['fastest']['total'])} a day: {usd(crit['fastest']['crypto'])} on the crypto "
            f"markets and {usd(crit['fastest']['fx_indices'])} on FX and indices; #614's decision D9 sets its budget at zero.", ""]

    out += ["## Honest flow's loss over each window", "",
            "House-wide, every genesis market, 102 weeks of hourly bars settled position by position on 10 s paths. `Mean` is the "
            "reading's mean; the quantiles are of each hour's highest reading. A negative reading is a house gain.", ""]
    for flow in ("current", "target"):
        h = honest[flow]
        out += [f"**{flow.capitalize()} flow** (honest income {usd(h['house']['income_per_day'])} a day):", ""]
        rows = []
        for m in ("realised", "marked"):
            for w in map(str, h["windows_min"]):
                s = h["house"][m][w]
                rows.append([m, w, usd(s["mean"]), usd(s["hourly_max_q"]["0.5"]), usd(s["hourly_max_q"]["0.99"]), usd(s["hourly_max_q"]["0.999"])])
        out += table(["Measure", "Window, min", "Mean", "Hourly max, median", "p99", "p99.9"], rows) + [""]

    out += ["### Per market, marked, 60 minutes (current flow)", ""]
    rows = []
    h = honest["current"]
    for sym, r in sorted(h["markets"].items(), key=lambda kv: -kv[1]["income_per_day"]):
        s = r["measures"]["marked"]["60"]
        t1 = next(t for t in s["thresholds"] if t["rate"] == 0.01)
        rows.append([sym, usd(r["income_per_day"]), usd(s["mean"]), usd(t1["threshold"]), pct(t1.get("raised_share")),
                     usd(r["exposure_q"]["0.99"]), usd(r["cap_at_reference_nav"]), pct(r["time_over_cap"])])
    out += table(["Market", "Income a day", "Mean", "Threshold at 1% of hours", "Time raised", "Exposure p99", "Cap at $107M NAV",
                  "Time over cap"], rows) + [""]

    out += ["## The window", "",
            "The house-wide marked reading's threshold at 1% of hours on each window, and the room it leaves an attacker a day.", ""]
    rows = []
    for w in map(str, honest["target"]["windows_min"]):
        cells = [w]
        for flow in ("current", "target"):
            t = next(t for t in honest[flow]["house"]["marked"][w]["thresholds"] if t["rate"] == 0.01)
            cells += [usd(t["threshold"]), usd(t.get("daily_room_mean")), usd(t.get("daily_room_p95"))]
        rows.append(cells)
    out += table(["Window, min", "Current: threshold", "room a day", "p95", "Target: threshold", "room a day", "p95"], rows) + [""]

    out += ["## Candidate thresholds", "",
            "Each threshold fires on honest flow in the stated share of hours; `time raised` adds the cooldown and the time the reading "
            "stays over it. `Room` is what an attacker can add a day before the reading meets the threshold: the sum over the day's "
            "disjoint windows of the threshold less honest flow's loss in each, an upper bound before each window's overshoot.", ""]
    for flow in ("current", "target"):
        rows = []
        for m in ("realised", "marked"):
            for w in ("60", "360", "1440"):
                for t in honest[flow]["house"][m][w]["thresholds"]:
                    rows.append([m, w, pct(t["rate"], 1), usd(t["threshold"]), pct(t["fire_share"]), pct(t.get("raised_share")),
                                 usd(t.get("daily_room_mean")), usd(t.get("daily_room_p95"))])
        out += [f"**House-wide, {flow} flow:**", ""] + table(
            ["Measure", "Window, min", "Fire rate", "Threshold", "Hours fired", "Time raised", "Room a day, mean", "p95"], rows) + [""]

    out += ["## Bad debt", "",
            "Honest flow's bad debt on the rogue study's sampled crypto hours (#549's recorded trades), as the share of a year's hours in "
            "which the reading over the window meets each threshold.", ""]
    rows = []
    for m in inputs_markets(grid):
        for w in ("1", "60"):
            rows.append([m, w] + [pct(grid_fire(grid, "bad_debt", w, t, m), 3) for t in (1.0, 1e3, 1e4, 2.5e4, 1e5)])
    out += table(["Market", "Window, min", "> $0", "$1k", "$10k", "$25k", "$100k"], rows) + [""]
    stress_bad = {r["market"]: [] for r in grid}
    for r in grid:
        if r["stratum"] == "stress":
            stress_bad[r["market"]].append(r["bad_debt_hour"])
    out += ["Honest bad debt in each of 2025-10-10's four stress hours: " +
            "; ".join(f"{m} {', '.join(usd(v) for v in vals)}" for m, vals in stress_bad.items() if vals) + ".", ""]
    for flow in ("current",):
        rows = []
        for w in ("60", "1440"):
            s = honest[flow]["house"]["bad_debt"][w]
            rows.append([w, usd(s["hourly_max_q"]["0.99"]), usd(s["hourly_max_q"]["0.999"])])
        out += ["House-wide bad debt on the bridged bars (gaps at reopenings and past a closed-out position's balance between 10 s "
                "bins; no jumps inside an hour):", ""] + table(["Window, min", "Hourly max p99", "p99.9"], rows) + [""]

    out += ["## 2025-10-10's unpriced pairs under each trigger", "",
            "$50M a side on BTC-USD and ETH-USD at 1% margin and tier 3's fee, over the day's four recorded hours. Without a loss "
            "trigger, each way of counting:", ""]
    out += table(["Pairs and moves", "House loss", "Spells"],
                 [[k, usd(v["house_loss"]), v["spells"]] for k, v in stress["current"]["untriggered"].items()]) + [""]
    pay = np.cumsum(stress["current"]["untriggered"]["pre-opened, from the last repricing"]["payoffs"])
    out += ["Pairs opened ahead are capital: each is $1M of margin over two accounts that have earned tier 2. The day's take by the "
            "number held, used on the first spells: " + "; ".join(f"{k} {usd(pay[min(k, len(pay)) - 1])}" for k in (1, 5, 10, 25, 50, len(pay))) + ".", ""]
    for flow in ("current", "target"):
        rows = []
        for c in stress[flow]["candidates"]:
            if c["fire_rate"] is not None and c["fire_rate"] > 0.05:
                continue
            th = c["threshold"]
            th_text = usd(th["house"]) if isinstance(th, dict) else usd(th)
            h, m = c["house"], c["market"]
            rows.append([c["measure"], c["window_min"], pct(c["fire_rate"], 1) if c["fire_rate"] is not None else "-", th_text,
                         pct(c.get("honest_raised_share", {}).get("house")), usd(h["pre_opened"]["house_loss"]), h["pre_opened"]["spells"],
                         usd(h["per_spell"]["house_loss"]), f"{h['pre_opened']['raised_minutes']:.0f}", usd(m["pre_opened"]["house_loss"]),
                         usd(m["per_spell"]["house_loss"])])
        out += [f"**Under each trigger, {flow} flow's honest loss as the background** (moves from the last repricing; the operator's "
                "better policy while raised):", ""] + table(
            ["Measure", "Window, min", "Honest fire rate", "Threshold, house-wide", "Honest time raised", "Pre-opened, house-wide", "Spells",
             "Per spell, house-wide", "Minutes raised", "Pre-opened, per market", "Per spell, per market"], rows) + [""]

    out += ["## Latency arbitrage and the fastest honest client under each trigger", "",
            "Each sits out the time the level is raised; its take falls by the share of it earned in raised time, from honest flow's "
            "time raised in each volatility stratum. Operator figures are its take (80% of its accounts' profit); the fastest client's "
            "are its whole take.", ""]
    rows = []
    for t in latency["triggers"]:
        if t["flow"] != "target" or t["measure"] != "marked":
            continue
        rows.append([t["scope"], t["window_min"], pct(t["fire_rate"], 1), usd(t["operator"]["crypto"]), usd(t["operator"]["fx_indices"]),
                     usd(t["fastest"]["crypto"]), usd(t["fastest"]["fx_indices"])])
    out += table(["Scope", "Window, min", "Fire rate", "Operator, crypto", "Operator, FX and indices", "Fastest, crypto",
                  "Fastest, FX and indices"], rows) + [""]
    out += ["**What reaches the fastest client without a trigger.** Its best day on each crypto market (the whole position at the first "
            "tier, an upper bound) with an extra spread on every fill, and with a floor under the fee at every hold:", ""]
    rows = []
    for m, r in latency["fastest_without_trigger"].items():
        zero_spread = next((k for k, v in r["spread"].items() if v <= 0), None)
        zero_fee = next((k for k, v in r["fee_floor"].items() if v <= 0), None)
        cost = latency["fee_floor_target_cost"].get(zero_fee) if zero_fee else None
        rows.append([m, usd(r["spread"]["0.0"]), f"{zero_spread} bps" if zero_spread else "past 20 bps",
                     f"{float(zero_fee):.0%}" if zero_fee else "past 100%", pct(cost, 1)])
    out += table(["Market", "Take a day, bound", "Extra spread a fill to zero", "Fee floor to zero",
                  "Target client's extra fee at that floor, share of its gross profit"], rows) + [""]
    text = "\n".join(out) + "\n"
    (results / "report.md").write_text(text)
    return text


def inputs_markets(grid: list) -> list:
    return sorted({r["market"] for r in grid})
